/**
 * The bookmark mark, in both states.
 *
 * ONE GLYPH, TWO FILLS, rather than two shapes. `fill` is the only difference —
 * `none` for a word that is not saved, `currentColor` for one that is — so the
 * outline never moves between states and the control cannot be read as two
 * different buttons. js/ used a heart (HeartFilled) for the same job; a bookmark
 * is the plainer metaphor for "saved to come back to", and app-v2 has no other
 * heart to be consistent with.
 *
 * `filled` is consumed rather than spread onto the <svg>, so React never sees an
 * unknown DOM attribute.
 */
export const Bookmark = ({ filled = false, ...props }) => (
  <svg
    aria-hidden="true"
    xmlns="http://www.w3.org/2000/svg"
    width="24"
    height="24"
    viewBox="0 0 24 24"
    fill={filled ? 'currentColor' : 'none'}
    stroke="currentColor"
    strokeWidth="2"
    strokeLinecap="round"
    strokeLinejoin="round"
    {...props}
  >
    <path d="M19 21l-7-5-7 5V5a2 2 0 0 1 2-2h10a2 2 0 0 1 2 2z" />
  </svg>
)

